export type RGB = [number, number, number];

export class PPMCanvas {
  readonly width: number;
  readonly height: number;
  private readonly data: Buffer;

  constructor(width = 720, height = 1280) {
    this.width = width;
    this.height = height;
    this.data = Buffer.alloc(width * height * 3);
  }

  setPixel(x: number, y: number, r: number, g: number, b: number): void {
    if (x < 0 || x >= this.width || y < 0 || y >= this.height) return;
    const idx = (y * this.width + x) * 3;
    this.data[idx] = r;
    this.data[idx + 1] = g;
    this.data[idx + 2] = b;
  }

  fillGradient(topColor: RGB, bottomColor: RGB): void {
    for (let y = 0; y < this.height; y++) {
      const t = y / this.height;
      const r = Math.round(topColor[0] * (1 - t) + bottomColor[0] * t);
      const g = Math.round(topColor[1] * (1 - t) + bottomColor[1] * t);
      const b = Math.round(topColor[2] * (1 - t) + bottomColor[2] * t);
      for (let x = 0; x < this.width; x++) {
        const dx = (x - this.width / 2) / (this.width / 2);
        const dy = (y - this.height / 2) / (this.height / 2);
        const vign = Math.max(0.68, 1 - (dx * dx + dy * dy) * 0.22);
        this.setPixel(x, y, Math.round(r * vign), Math.round(g * vign), Math.round(b * vign));
      }
    }
  }

  fillRect(x: number, y: number, w: number, h: number, color: RGB): void {
    const startX = Math.max(0, x);
    const endX = Math.min(this.width, x + w);
    const startY = Math.max(0, y);
    const endY = Math.min(this.height, y + h);
    for (let py = startY; py < endY; py++) {
      for (let px = startX; px < endX; px++) {
        this.setPixel(px, py, color[0], color[1], color[2]);
      }
    }
  }

  drawCard(x: number, y: number, w: number, h: number, borderColor: RGB, fillColor: RGB, borderWidth = 3): void {
    this.fillRect(x, y, w, h, fillColor);
    this.fillRect(x, y, w, borderWidth, borderColor);
    this.fillRect(x, y + h - borderWidth, w, borderWidth, borderColor);
    this.fillRect(x, y, borderWidth, h, borderColor);
    this.fillRect(x + w - borderWidth, y, borderWidth, h, borderColor);
  }

  drawChar(ch: string, startX: number, startY: number, scale: number, color: RGB): void {
    const glyph = FONT[ch] || FONT[ch.toUpperCase()] || FONT['?'];
    if (!glyph) return;
    for (let row = 0; row < 8; row++) {
      const byte = glyph[row];
      for (let col = 0; col < 8; col++) {
        if (byte & (1 << col)) {
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              this.setPixel(startX + col * scale + sx, startY + row * scale + sy, color[0], color[1], color[2]);
            }
          }
        }
      }
    }
  }

  measureText(text: string, scale: number): number {
    return text.length * 8 * scale;
  }

  drawText(text: string, startX: number, startY: number, scale: number, color: RGB): void {
    for (let i = 0; i < text.length; i++) {
      this.drawChar(text[i], startX + i * 8 * scale, startY, scale, color);
    }
  }

  drawCenteredText(text: string, y: number, scale: number, color: RGB): void {
    const textWidth = this.measureText(text, scale);
    const startX = Math.max(20, Math.floor((this.width - textWidth) / 2));
    this.drawText(text, startX, y, scale, color);
  }

  drawBadge(text: string, y: number, fgColor: RGB, bgColor: RGB, scale = 3): void {
    const textWidth = this.measureText(text, scale);
    const padX = 24;
    const padY = 12;
    const cardW = textWidth + padX * 2;
    const cardH = 8 * scale + padY * 2;
    const cardX = Math.floor((this.width - cardW) / 2);
    this.drawCard(cardX, y, cardW, cardH, fgColor, bgColor, 2);
    this.drawText(text, cardX + padX, y + padY, scale, fgColor);
  }

  drawWrapped(text: string, startX: number, startY: number, maxWidth: number, scale: number, color: RGB, lineHeight: number): number {
    const words = text.split(/\s+/);
    let line = "";
    let curY = startY;
    const lines: string[] = [];

    for (const word of words) {
      const testLine = line ? line + " " + word : word;
      if (this.measureText(testLine, scale) <= maxWidth) {
        line = testLine;
      } else {
        if (line) lines.push(line);
        line = word;
      }
    }
    if (line) lines.push(line);

    for (const l of lines) {
      this.drawText(l, startX, curY, scale, color);
      curY += lineHeight;
    }
    return curY;
  }

  toBuffer(): Buffer {
    const header = Buffer.from(`P6\n${this.width} ${this.height}\n255\n`);
    return Buffer.concat([header, this.data]);
  }

  async saveToFile(filePath: string): Promise<void> {
    await fs.writeFile(filePath, this.toBuffer());
  }
}

